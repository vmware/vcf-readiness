                                   '<li><strong>Pure Standard-Library Fallback (Zero-Dependency):</strong> When '
                                   'running from pure source on bare bastion or air-gapped hosts without external '
                                   'wheels, the vault uses an OpenSSL-backed Encrypt-then-MAC construction built '
                                   'exclusively from Python stdlib primitives (<code>hashlib</code>, '
                                   '<code>hmac</code>, <code>secrets</code>):</li>\n'
                                   '</ol>\n'
                                   '<div class="docs-table-wrap"><table class="docs-table">\n'
                                   '<thead><tr><th>Step</th><th>Primitive</th><th>Parameters</th></tr></thead>\n'
                                   '<tbody>\n'
                                   '<tr><td>Key derivation</td><td>PBKDF2-HMAC-SHA256 '
                                   '(<code>hashlib.pbkdf2_hmac</code>)</td><td>600,000 iterations, 16-byte random '
                                   'salt, 32-byte master key; iteration floor of 100,000 is enforced on '
                                   'read</td></tr>\n'
                                   '<tr><td>Sub-key separation</td><td>HMAC-SHA256(master, label)</td><td>Distinct '
                                   'labels for the encryption key and the MAC key</td></tr>\n'
                                   '<tr><td>Confidentiality</td><td>HMAC-SHA256 counter-mode keystream XOR '
                                   'plaintext</td><td>Fresh 16-byte random nonce (<code>secrets.token_bytes</code>) on '
                                   'every save</td></tr>\n'
                                   '<tr><td>Integrity / authenticity</td><td>HMAC-SHA256 over <code>header ‖ nonce ‖ '
                                   'ciphertext</code></td><td>Verified with <code>hmac.compare_digest</code> '
                                   '<strong>before</strong> any decryption; the canonical JSON header (format, '
                                   'version, KDF parameters, cipher id) is bound as associated data so lowering the '
                                   'iteration count or swapping the salt is detected</td></tr>\n'
                                   '</tbody></table></div>\n'
                                   '<p>In both modes, the canonical JSON header (format, version, KDF parameters, '
                                   'cipher ID) is bound into the authentication tag as Additional Authenticated Data '
                                   '(AAD), ensuring any header tampering (such as lowering iteration counts or '
                                   'swapping the cipher ID) causes immediate verification failure. A wrong passphrase '
                                   'and a tampered file are indistinguishable by design.</p>\n'
                                   '<p><strong>Storage and hygiene</strong></p>\n'
                                   '<ul>\n'
                                   '<li>Location: <code>~/.vcf-readiness/credentials.vault</code> (override with '
                                   '<code>--vault PATH</code>). Written atomically (temp file + '
                                   '<code>os.replace</code>) with <code>0600</code> permissions; on Windows an '
                                   '<code>icacls /inheritance:r /grant:r &lt;user&gt;:(R,W)</code> ACL is '
                                   'applied.</li>\n'
                                   '<li>Contents: JSON envelope with base64 fields — no plaintext usernames, '
                                   'passwords, hostnames, or notes are ever on disk.</li>\n'
                                   '<li>Passphrases and BMC passwords are never accepted on the command line '
                                   '(<code>argv</code> is visible to other processes); they are read via '
                                   '<code>getpass</code> or from an environment variable you name '
                                   '(<code>--vault-passphrase-env</code>, <code>--password-env</code>).</li>\n'
                                   '<li><code>list</code> / <code>GET /api/vault/entries</code> return targets, kinds, '
                                   'usernames, and notes — <strong>never passwords</strong>. There is deliberately no '
                                   '"reveal" or "export plaintext" command.</li>\n'
                                   '<li>Resolution precedence at scan time: exact host → longest-prefix CIDR → '
                                   '<code>default</code>. The resolved map is passed directly to the scanner and '
                                   'dropped (<code>lock()</code>) when the scan ends.</li>\n'
                                   '</ul>\n'
