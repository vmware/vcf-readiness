                                   '<h2 id="34-ephemeral-remote-execution-and-jump-hosts-experimental">3.4 Ephemeral '
                                   'remote execution and jump hosts (Experimental)</h2>\n'
                                   '<blockquote><strong>Preview / Experimental Status:</strong> Ephemeral remote '
                                   'execution via jump hosts is an experimental capability provided for preview '
                                   'testing in isolated or network-segmented environments.</blockquote>\n'
                                   '<p>A remote scan is still started from the workstation UI on '
                                   '<code>127.0.0.1</code>. The workstation opens SSH to a Linux jump host and runs a '
                                   'short-lived copy of the collector.</p>\n'
                                   '<ul>\n'
                                   '<li>The jump host process is unprivileged. It writes only under '
                                   '<code>/tmp/vcfr_remote_&lt;hex&gt;</code> with mode <code>0700</code>.</li>\n'
                                   "<li>BMC passwords are sent on the collector's stdin (<code>--creds-stdin</code>). "
                                   'They are not placed in argv and not written into the remote directory.</li>\n'
