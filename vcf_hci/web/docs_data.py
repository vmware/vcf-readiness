                                   '<h2 id="7-local-web-server-hardening-specification">7. Local Web Server Hardening '
                                   'Specification</h2>\n'
                                   '<p>When running the interactive Browser UI (<code>vcfr_web.py</code>), the '
                                   'internal HTTP server (<code>vcf_hci.web.server</code>) implements enterprise-grade '
                                   'application security controls:</p>\n'
                                   '<pre><code class="language-mermaid">flowchart TD\n'
                                   '    Req[Incoming HTTP Request] --&gt; OriginCheck{Host / Origin Valid?}\n'
                                   '    OriginCheck -- No --&gt; Block403[403 Forbidden: Invalid Host/Origin]\n'
                                   '    OriginCheck -- Yes --&gt; AuthCheck{Valid Launch Token or Session?}\n'
                                   '    AuthCheck -- No --&gt; Block401[401/403 Unauthorized: Invalid Token]\n'
                                   '    AuthCheck -- Yes --&gt; SSRFCheck{Target in Cloud Metadata or Prohibited IP?}\n'
                                   '    SSRFCheck -- Yes --&gt; BlockSSRF[400 Bad Request: SSRF Prohibited Target]\n'
                                   '    SSRFCheck -- No --&gt; BodyCap{Payload &lt;= 32MB?}\n'
                                   '    BodyCap -- No --&gt; Block413[413 Payload Too Large]\n'
                                   '    BodyCap -- Yes --&gt; ProcessReq[Process Request &amp; Inject CSP / Security '
                                   'Headers]</code></pre>\n'
                                   '<ol>\n'
                                   '<li><strong>Loopback by default:</strong> Binds to <code>127.0.0.1</code> unless '
                                   'the operator explicitly requests a non-loopback listener. That mode is the '
                                   'TLS-only case in item 2. Remote access is off by default.</li>\n'
                                   '<li><strong>One-time launch token.</strong> At startup the server generates a '
                                   '128-bit token (<code>secrets.token_hex(16)</code>) and prints it once '
                                   '(<code>http://127.0.0.1:7182/?token=...</code> on loopback). That value is '
                                   'accepted only on <code>GET /</code>, and only until the browser presents the '
                                   'session cookie minted from it. A retry of the same URL is accepted for at most 5 '
                                   'seconds, and only when that cookie has not been presented yet, so a lost redirect '
                                   'can finish. It is not stored as the session, it is not accepted as '
                                   '<code>X-Server-Token</code>, and it does not authorize scan or credential APIs. '
                                   'Redemption answers <code>302</code> to <code>/</code> with <code>Set-Cookie: '
                                   'vcf_session=&lt;new 192-bit token&gt;; Path=/; HttpOnly; SameSite=Strict</code> '
                                   'and <code>Cache-Control: no-store</code>, so the token leaves the address bar. '
                                   'Debug access logs redact <code>token=</code>. A missing session is '
                                   '<code>401</code> on <code>GET /</code> and <code>403</code> on every other '
                                   'route.</li>\n'
                                   '</ol>\n'
                                   '<p><strong>Network-exposed listeners are HTTPS-only.</strong> '
                                   '<code>--allow-remote</code>, or any <code>--bind</code> other than '
                                   '<code>127.0.0.1</code>, <code>::1</code>, or <code>localhost</code>, refuses to '
                                   'start unless <code>--tls-cert</code> and <code>--tls-key</code> are both set. The '
                                   'socket is wrapped with TLS 1.2+. Startup prints the certificate SHA-256 '
                                   'fingerprint and does not open a browser, so the one-time URL is not consumed on '
                                   'the server host. On that listener the session cookie also carries '
                                   '<code>Secure</code>. Loopback HTTP, including an SSH local forward, does not set '
                                   '<code>Secure</code> (browsers will not store a Secure cookie on '
                                   '<code>http://127.0.0.1</code>). Prefer the SSH forward in '
                                   '<code>docs/INSTALL.md</code> over binding the UI to a reachable interface.</p>\n'
                                   '<ol>\n'
                                   '<li><strong>Anti-CSRF &amp; DNS-Rebinding Defense:</strong> Request validation '
                                   'inspects <code>Host</code>, <code>Origin</code>, and <code>Referer</code> headers. '
                                   'On the default loopback listener, a host that is not loopback or the bound address '
                                   'is rejected with <code>403 Forbidden</code>. <code>--allow-remote</code> checks '
                                   'the addressed host instead of limiting the check to loopback.</li>\n'
                                   '<li><strong>Security Response Headers:</strong> UI and docs responses '
                                   'include:</li>\n'
                                   '</ol>\n'
                                   '<ul>\n'
                                   "<li><code>Content-Security-Policy: default-src 'self' 'unsafe-inline' data:; "
                                   "connect-src 'self';</code></li>\n"
                                   '<li><code>X-Frame-Options: SAMEORIGIN</code></li>\n'
                                   '<li><code>Cache-Control: no-store</code></li>\n'
                                   '<li><code>Referrer-Policy: no-referrer</code></li>\n'
                                   '</ul>\n'
                                   '<p>HTML under <code>/reports/</code> is a different document. Inline script stays '
                                   'so fleet and host controls keep working. Those responses set <code>connect-src '
                                   "'none'</code>, <code>Cross-Origin-Opener-Policy: noopener-allow-popups</code>, and "
                                   '<code>Referrer-Policy: no-referrer</code>, and the UI opens them with '
                                   '<code>noopener</code>. <code>POST /api/keychain/store</code> and <code>POST '
                                   '/api/keychain/retrieve</code> also require a <code>Referer</code> whose path is '
                                   '<code>/</code>, so a report document cannot read or write OS-keychain secrets with '
                                   'the session cookie.</p>\n'
                                   '<ol>\n'
                                   '<li><strong>SSRF Target Protection:</strong> The target parser strictly validates '
                                   'scanning targets and blocks Server-Side Request Forgery attempts aimed at cloud '
                                   'metadata endpoints (<code>169.254.169.254</code>, <code>169.254.170.2</code>, '
                                   '<code>fd00:ec2::254</code>, <code>metadata.google.internal</code>).</li>\n'
                                   '<li><strong>DoS Mitigation:</strong> Enforces a 32MB maximum request body size cap '
                                   '(<code>MAX_BODY_SIZE</code>) to prevent memory exhaustion attacks.</li>\n'
                                   '<li><strong>Credential Vault Endpoints (<code>/api/vault/*</code>, '
                                   'opt-in):</strong> <code>status</code>, <code>create</code>, <code>unlock</code>, '
                                   '<code>lock</code>, <code>entries</code> (list / upsert), <code>remove</code>, '
                                   '<code>import-csv</code>, <code>coverage</code>. Every one of them:</li>\n'
                                   '</ol>\n'
                                   '<ul>\n'
                                   '<li>requires the launch-token session <strong>and</strong> passes the same-origin '
                                   'check (<code>Sec-Fetch-Site</code> / <code>Origin</code> port) used by the '
                                   'OS-keychain endpoints;</li>\n'
                                   '<li>is refused with <code>403</code> whenever the server was started with '
                                   '<code>--allow-remote</code> (the vault is a local-workstation feature only);</li>\n'
                                   '<li>never returns a password in any response body — entry listings and coverage '
                                   'previews are password-free;</li>\n'
                                   '<li>answers <code>423 Locked</code> when no vault is unlocked, <code>401</code> on '
                                   'a wrong passphrase (with a 0.5 s delay on top of the PBKDF2 cost), and '
                                   '<code>409</code> if a create would overwrite an existing vault.</li>\n'
                                   '</ul>\n'
                                   '<p>At most one vault is held unlocked in server memory '
                                   '(<code>vcf_hci/web/vault_session.py</code>); it auto-locks after 60 minutes idle '
                                   'and on <code>/api/shutdown</code> or Ctrl-C. When a scan is submitted with '
                                   '<code>use_vault: true</code>, credentials are resolved on the server; the '
                                   'browser-supplied username/password become only a fallback for targets with no '
                                   'vault match. <code>use_vault</code> defaults to <code>false</code> and the UI '
                                   'checkbox is disabled until a vault is unlocked.</p>\n'
